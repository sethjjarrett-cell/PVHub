/* Regenerate src/pdfWorkerText.js from the installed pdfjs-dist.
 *
 * The worker is inlined as a string so the application makes no CDN
 * call and works offline. The cost of that is a file which must be
 * regenerated whenever pdfjs-dist moves: pdf.js refuses to run a worker
 * whose version does not match the API ("The API version X does not
 * match the Worker version Y"), and because the PDF paths are optional
 * extras the failure shows up as one unreadable file rather than as a
 * broken build. It went unnoticed for exactly that reason.
 *
 *   npm run gen:pdf-worker
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const version = require("pdfjs-dist/package.json").version;
const SRC = "node_modules/pdfjs-dist/legacy/build/pdf.worker.min.mjs";
const OUT = "src/pdfWorkerText.js";

const src = readFileSync(SRC, "utf8");
if (/(^|\n)\s*(import|export)\s/.test(src)) {
  console.error(`${SRC} contains top-level import/export, so it cannot run as a classic\n`
    + "blob worker. Load it as a module worker instead of inlining it.");
  process.exit(1);
}

writeFileSync(OUT,
  `// generated by scripts/genPdfWorker.mjs from pdfjs-dist ${version} — never hand-edit\n`
  + `export const PDF_WORKER_VERSION = ${JSON.stringify(version)};\n`
  + `export default ${JSON.stringify(src)};\n`);

console.log(`${OUT} regenerated from pdfjs-dist ${version} (${src.length} bytes)`);
